CREATE DATABASE IF NOT EXISTS CAFE;
USE SCHEMA CAFE.PUBLIC;

CREATE OR REPLACE TABLE PRODUCTORES (
  PRODUCTOR_ID STRING, REGION STRING, COOPERATIVA STRING, HECTAREAS NUMBER(6,1), CERTIFICACION STRING, GEOLOCALIZADO STRING);

CREATE OR REPLACE TABLE LOTES (  -- mismo orden de columnas que lotes.csv (la carga va por posición)
  LOTE_ID STRING, FECHA_COMPRA DATE, MES STRING, MES_FECHA DATE, PRODUCTOR_ID STRING, REGION STRING, SACOS_60KG NUMBER,
  PUNTAJE_SCA NUMBER(4,1), FACTOR_RENDIMIENTO NUMBER(5,1), ESPECIAL_PRIMA STRING, GEOLOCALIZADO STRING,
  DESTINO_MERCADO STRING, COMPRADOR STRING, ESTADO STRING, PRECIO_C_USD_LB NUMBER(6,3), DIFERENCIAL_USD_LB NUMBER(6,3),
  PRECIO_VENTA_USD_LB NUMBER(6,3), VENTAS_USD NUMBER, MARGEN_USD NUMBER);

CREATE OR REPLACE TABLE EMBARQUES (
  EMBARQUE_ID STRING, FECHA DATE, MES STRING, PUERTO STRING, DESTINO_MERCADO STRING, COMPRADOR STRING,
  CONTENEDORES NUMBER, DIAS_DOCUMENTOS NUMBER, RETRASO_DIAS NUMBER, FECHA_PROMETIDA DATE);

CREATE OR REPLACE TABLE RECLAMOS (
  RECLAMO_ID STRING, FECHA DATE, MES STRING, EMBARQUE_ID STRING, COMPRADOR STRING, DESTINO_MERCADO STRING,
  MOTIVO STRING, COSTO_USD NUMBER);

CREATE OR REPLACE TABLE MERCADO_DIARIO (FECHA DATE, CONTRATO_C_USD_LB NUMBER(8,4), TRM_COP_USD NUMBER(10,2), PRECIO_REF_COP_KG NUMBER);

CREATE OR REPLACE TABLE PRESUPUESTO (RUBRO STRING, ASIGNADO_MUSD NUMBER(8,1), EJECUTADO_MUSD NUMBER(8,1));

-- Comprobación: deben salir 1.250.000 sacos y 71 % de lotes con geolocalización.
SELECT SUM(SACOS_60KG) AS SACOS,
       ROUND(100 * COUNT_IF(GEOLOCALIZADO = 'Sí') / COUNT(*), 1) AS PCT_GEOLOCALIZADOS
FROM LOTES;

-- La misma cifra para el asistente del kit (python -m kit.snowflake traer --consulta "…"):
SELECT 'pct_lotes_con_geolocalizacion' AS CLAVE,
       'Porcentaje de lotes con la geolocalización de sus fincas (trazabilidad para la Unión Europea)' AS DESCRIPCION,
       ROUND(100 * COUNT_IF(GEOLOCALIZADO = 'Sí') / COUNT(*)) AS VALOR, '%' AS UNIDAD, 0 AS DECIMALES,
       'Snowflake: CAFE.PUBLIC.LOTES' AS FUENTE
FROM LOTES;
